begin;
create extension if not exists pgtap with schema extensions;
set local search_path=extensions,public;
select plan(8);
set local role anon;
select is((select count(*)::integer from public.profile),1,'anonymous visitors can read profile');
select is((select count(*)::integer from public.projects),3,'anonymous visitors can read supplied public projects');
select throws_ok($$insert into public.projects(title,description) values ('Unauthorised','blocked')$$,'42501','anonymous users cannot insert projects');
select throws_ok($$select * from public.messages$$,'42501','anonymous users cannot read the contact inbox');
reset role;
set local role authenticated;
select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-000000000001',true);
select set_config('request.jwt.claim.role','authenticated',true);
select ok(public.is_admin() is false,'ordinary authenticated users are not admins');
select throws_ok($$insert into public.projects(title,description) values ('Unauthorised','blocked')$$,'42501','non-admin authenticated users cannot insert projects');
select throws_ok($$update public.projects set title='Unauthorised' where title='EchoGuard'$$,'42501','non-admin authenticated users cannot edit projects');
reset role;
select ok(not exists(select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname in ('administrators manage portfolio files','visitors read only published portfolio files')),'browser Storage policies are absent; Edge Functions mediate files');
select * from finish();
rollback;
